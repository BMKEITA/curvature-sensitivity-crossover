#!/usr/bin/env bash
# =============================================================================
# run_all_experiments.sh (v4 — final, all reviewer points addressed + fixes)
#
# Addresses:
#   [REV 6] γ sensitivity (3 runs), m* stability (parsed from logs),
#           sd sensitivity (multiplicative factor κ ∈ {0.5, 1.0, 2.0})
#   [REV 7] verification of the anonymous reproducibility package
#   [FIX 1] SD_FACTOR (multiplicative) replaces the broken SD_FIXED (absolute)
#   [FIX 3] holm_correction_results.txt is produced by fu_v4_8_gpu.py
#   [FIX 4] Old sens_sd_*.log files are cleared before regeneration
#
# Usage:
#   bash run_all_experiments.sh                     # full run + sensitivity
#   SKIP_SENSITIVITY=1 bash run_all_experiments.sh  # skip sensitivity (faster)
#   SKIP_RUN=1 bash run_all_experiments.sh          # verify existing logs only
# =============================================================================
set -euo pipefail

# ------------------------- configuration ------------------------------------
: "${B:=3000}"
: "${SEEDS:=30}"
: "${M:=300}"
: "${OMP_NUM_THREADS:=4}"
: "${SKIP_RUN:=0}"
: "${SKIP_SENSITIVITY:=0}"
export OMP_NUM_THREADS

if [[ $# -gt 0 ]]; then
    DATASETS=("$@")
else
    DATASETS=(mnist cifar10 cifar100)
fi

GAMMA=1e-2
DELTA=1e-5
EPS_DP=4.0
LEVELS="0.10 0.15 0.25"
PRIM_LEVEL=0.10
ALPHA=0.05
KS="1 2 5 10"
SEQ_NT=12
NUS="50 100 150 200 300 450 700 1000 1500 2200 3200"
NUS2="100 200 300 450 700 1000 1500 2200 3200 4800 6400 9600 12800 19200"
EPS="0.25 0.5 1 2 4 16"

# ------------------------- helpers ------------------------------------------
ts()    { date +"%Y-%m-%d %H:%M:%S"; }
log()   { echo "[$(ts)] $*"; }
fail()  { echo "[$(ts)] ERROR: $*" >&2; exit 1; }
hr()    { printf '%s\n' "==============================================================================="; }

npz_for() {
    case "$1" in
        mnist)    echo "dino_mnist.npz" ;;
        cifar10)  echo "dino_cifar10.npz" ;;
        cifar100) echo "dino_cifar100.npz" ;;
        *)        fail "unknown dataset: $1" ;;
    esac
}

c_for() {
    case "$1" in
        mnist)    echo 10 ;;
        cifar10)  echo 10 ;;
        cifar100) echo 100 ;;
        *)        fail "unknown dataset: $1" ;;
    esac
}

# ------------------------- environment check --------------------------------
log "Environment check"
python -c "import torch, numpy, scipy; \
           print(f'  torch  = {torch.__version__}'); \
           print(f'  cuda   = {torch.cuda.is_available()}'); \
           print(f'  device = {torch.cuda.get_device_name(0) if torch.cuda.is_available() else \"cpu\"}'); \
           print(f'  numpy  = {numpy.__version__}'); \
           print(f'  scipy  = {scipy.__version__}')" \
    || fail "python deps missing"

[[ -f fu_v4_3.py     ]] || fail "fu_v4_3.py not found"
[[ -f fu_v4_8_gpu.py ]] || fail "fu_v4_8_gpu.py not found"

for ds in "${DATASETS[@]}"; do
    npz=$(npz_for "$ds")
    [[ -f "$npz" ]] || fail "missing $npz (required for $ds)"
done

mkdir -p logs
# [FIX 3] Clear the old Holm file on a fresh run so append doesn't accumulate
# across runs. The file is regenerated by fu_v4_8_gpu.py at the end of each run.
if [[ "$SKIP_RUN" != "1" ]]; then
    rm -f holm_correction_results.txt
fi

log "Datasets:    ${DATASETS[*]}"
log "B=${B}  SEEDS=${SEEDS}  M=${M}  OMP_NUM_THREADS=${OMP_NUM_THREADS}"
log "gamma=${GAMMA}  delta=${DELTA}  eps_dp=${EPS_DP}"
log "primary level (rand)=0.10  primary level (high)=0.25"
log "SKIP_RUN=${SKIP_RUN}  SKIP_SENSITIVITY=${SKIP_SENSITIVITY}"
hr

# ------------------------- steps 0-3 (skip if SKIP_RUN=1) -------------------
if [[ "$SKIP_RUN" != "1" ]]; then
    log "STEP 0/5: Sigma / NP consistency check"
    { python fu_v4_8_gpu.py --check_sigma 2>&1; } | tee logs/00_check_sigma.log
    hr

    log "STEP 1/5: CPU smoke test"
    { python fu_v4_3.py --quick 2>&1; } | tee logs/01_cpu_quick.log
    log "CPU smoke test passed"
    hr

    log "STEP 2/5: GPU smoke test"
    {
        python fu_v4_8_gpu.py \
            --features "" --both_strata --seeds 4 --M 50 --B 100 \
            --seq_nus 50 200 --seq_nus2 100 400 1600 --seq_eps 4 16 \
            2>&1
    } | tee logs/02_gpu_quick.log
    log "GPU smoke test passed"
    hr

    for ds in "${DATASETS[@]}"; do
        npz=$(npz_for "$ds")
        c=$(c_for "$ds")
        log "STEP 3/5: Full run for ${ds} (features=${npz}, c=${c})"
        log "  Expect ~4-6 hours per stratum on a TITAN Xp."

        python fu_v4_8_gpu.py \
            --features "${npz}" --c "${c}" \
            --gamma "${GAMMA}" --delta "${DELTA}" --eps_dp "${EPS_DP}" \
            --seeds "${SEEDS}" --M "${M}" --B "${B}" \
            --alpha "${ALPHA}" --levels ${LEVELS} --prim_level "${PRIM_LEVEL}" \
            --ks ${KS} --seq_nt "${SEQ_NT}" \
            --seq_nus ${NUS} --seq_nus2 ${NUS2} --seq_eps ${EPS} \
            --both_strata \
            2>&1 | tee "logs/03_${ds}.log"

        log "  Finished ${ds}"
        hr
    done
else
    log "SKIP_RUN=1: skipping steps 0-3, going to verification."
    hr
fi

# --------------------- [REV 6] step 4: sensitivity analyses ----------------
if [[ "$SKIP_RUN" != "1" ]] && [[ "$SKIP_SENSITIVITY" != "1" ]]; then
    log "STEP 4/6: Sensitivity analyses (γ, sd) on CIFAR-100 [REV 6]"
    hr

    # --- γ sensitivity: three values on CIFAR-100 ---
    log "  [REV 6] γ sensitivity: γ ∈ {0.001, 0.01, 0.1} on CIFAR-100"
    for gamma in 0.001 0.01 0.1; do
        log "    Running with γ=${gamma} ..."
        python fu_v4_8_gpu.py \
            --features dino_cifar100.npz --c 100 \
            --gamma "${gamma}" --delta "${DELTA}" --eps_dp "${EPS_DP}" \
            --seeds 10 --M "${M}" --B 500 \
            --seq_nus ${NUS} --seq_nus2 ${NUS2} --seq_eps ${EPS} \
            --both_strata \
            2>&1 | tee "logs/sens_gamma_${gamma}_cifar100.log"
    done

    # --- [FIX 1] sd sensitivity: multiplicative factor κ ∈ {0.5, 1.0, 2.0} on CIFAR-10/100 ---
    log "  [REV 6] sd sensitivity: κ · sd_calibrated for κ ∈ {0.5, 1.0, 2.0}"
    # [FIX 4] Remove the old (broken) sens_sd_*.log files before regeneration.
    rm -f logs/sens_sd_*.log
    for ds in cifar10 cifar100; do
        npz=$(npz_for "$ds")
        c=$(c_for "$ds")
        for kappa in 0.5 1.0 2.0; do
            log "    Running ${ds} with SD_FACTOR=${kappa} ..."
            SD_FACTOR="${kappa}" python fu_v4_8_gpu.py \
                --features "${npz}" --c "${c}" \
                --gamma "${GAMMA}" --delta "${DELTA}" --eps_dp "${EPS_DP}" \
                --seeds 10 --M "${M}" --B 500 \
                --seq_nus ${NUS} --seq_nus2 ${NUS2} --seq_eps ${EPS} \
                --both_strata \
                2>&1 | tee "logs/sens_sd_${ds}_kappa${kappa}.log"
        done
    done

    # --- m* stability: extract from the main logs ---
    log "  [REV 6] m* stability: extracting from main logs"
    for ds in "${DATASETS[@]}"; do
        f="logs/03_${ds}.log"
        if [[ -f "$f" ]]; then
            log "    ${ds}: m* distribution"
            grep -A 8 "mstar distribution" "$f" | head -10 | sed 's/^/      /'
        fi
    done
    hr
else
    log "STEP 4/6: sensitivity analyses skipped (SKIP_RUN=1 or SKIP_SENSITIVITY=1)"
    hr
fi

# ------------------------- step 5: verification -----------------------------
log "STEP 5/6: Verify each dataset's log [REV 1-7]"
FAILURES=0
WARNINGS=0
for ds in "${DATASETS[@]}"; do
    log "Checking logs/03_${ds}.log"
    f="logs/03_${ds}.log"
    [[ -f "$f" ]] || { log "  MISSING: $f"; FAILURES=$((FAILURES+1)); continue; }

    # [REV 6 + FIX B1] mstar non-degenerate
    if grep -q "mstar distribution per B epsilon" "$f"; then
        mstar_lines=$(grep -A 6 "mstar distribution" "$f" | grep "eps=" | head -8)
        n_multi=$(echo "$mstar_lines" | grep -cE "\{[^}]*:[^}]*," || true)
        if [[ "$n_multi" -ge 1 ]]; then
            log "  [REV 6] ✓ mstar non-degenerate (${n_multi} rows with >1 key)"
        else
            log "  [REV 6] [WARN] mstar looks degenerate"
            WARNINGS=$((WARNINGS+1))
        fi
    else
        log "  [REV 6] [FAIL] mstar distribution line missing"
        FAILURES=$((FAILURES+1))
    fi

    # [REV 2] FPR centered on alpha
    bad_fpr=$(awk '
        /^######## FPR sans suppression/ { in_fpr=1; next }
        /^########/                     { in_fpr=0 }
        in_fpr && /0\.[0-9]+\/0\.[0-9]+\/0\.[0-9]+/ {
            line=$0
            while (match(line, /0\.[0-9]+\/0\.[0-9]+\/0\.[0-9]+/)) {
                tok = substr(line, RSTART, RLENGTH)
                split(tok, a, "/")
                for (i = 1; i <= 3; i++) {
                    v = a[i] + 0
                    if (v > 0.10) { print "  [REV 2] [FAIL] FPR=" v " > 0.10"; exit 1 }
                    if (v > 0.07) { print "  [REV 2] [WARN] FPR=" v " > 0.07"; exit 0 }
                }
                line = substr(line, RSTART + RLENGTH)
            }
        }
    ' "$f" || true)

    if echo "$bad_fpr" | grep -q "\[FAIL\]"; then
        log "$bad_fpr"; FAILURES=$((FAILURES+1))
    elif echo "$bad_fpr" | grep -q "\[WARN\]"; then
        log "  [REV 2] [WARN] marginal FPR detected"
        WARNINGS=$((WARNINGS+1))
    else
        log "  [REV 2] ✓ all FPR base/ml/worst <= 0.07"
    fi

    # [REV 2] A2 un-censored
    a2_ml_line=$(grep "A2   bruit aniso (weights)" "$f" | head -1)
    if [[ -z "$a2_ml_line" ]]; then
        log "  [REV 2] [FAIL] A2 frontier missing"
        FAILURES=$((FAILURES+1))
    elif echo "$a2_ml_line" | grep -qE "n/d|  cens\."; then
        log "  [REV 2] [WARN] A2 frontier has censored cells:"
        WARNINGS=$((WARNINGS+1))
    else
        log "  [REV 2] ✓ A2 frontier un-censored"
    fi

    # [REV 1] MNIST DiD positive and significant
    did_ml_b4=$(grep "Crossover DiD.*B4 (stats UB)" "$f" | head -1)
    did_ml_b4w=$(grep "Crossover DiD.*B4_w" "$f" | head -1)
    if [[ -z "$did_ml_b4" ]] || [[ -z "$did_ml_b4w" ]]; then
        log "  [REV 1] [FAIL] DiD lines missing"
        FAILURES=$((FAILURES+1))
    else
        for label_line in "B4|$did_ml_b4" "B4_w|$did_ml_b4w"; do
            label="${label_line%%|*}"; line="${label_line#*|}"
            if echo "$line" | grep -qE "p = 0\.0[0-4]"; then
                log "  [REV 1] ✓ DiD vs ${label} significant under ml"
            else
                log "  [REV 1] [WARN] DiD vs ${label} not significant under ml"
                WARNINGS=$((WARNINGS+1))
            fi
        done
    fi

    # [REV 4] Composition mode visible
    if grep -q "\[REV 4\] Composition mode" "$f"; then
        log "  [REV 4] ✓ Composition mode visible in log"
    else
        log "  [REV 4] [WARN] Composition mode not reported"
        WARNINGS=$((WARNINGS+1))
    fi

    # [REV 3] H_s/H_w on CIFAR-100 correctly non-significant
    if [[ "$ds" == "cifar100" ]]; then
        if grep -q "H_w  : cout(A2) - cout(B4 weights) > 0.*+12.00" "$f"; then
            log "  [REV 3] [FAIL] H_w CIFAR-100 reported as +12.00"
            FAILURES=$((FAILURES+1))
        else
            log "  [REV 3] ✓ H_w CIFAR-100 correctly non-significant"
        fi
    fi

    hr
done

# [REV 5] Holm file exists and has content
log "STEP 5b/6: Check Holm correction file [REV 5]"
if [[ -f "holm_correction_results.txt" ]]; then
    n_lines=$(wc -l < holm_correction_results.txt)
    if [[ "$n_lines" -ge 2 ]]; then
        log "  [REV 5] ✓ holm_correction_results.txt exists (${n_lines} lines)"
    else
        log "  [REV 5] [WARN] holm_correction_results.txt exists but is nearly empty (${n_lines} lines)"
        WARNINGS=$((WARNINGS+1))
    fi
else
    log "  [REV 5] [FAIL] holm_correction_results.txt missing"
    FAILURES=$((FAILURES+1))
fi
hr

# [REV 7] Anonymous package
log "STEP 5c/6: Verify anonymous reproducibility package [REV 7]"
if [[ -f "supplementary_code/README.md" ]] && [[ -d "supplementary_code/logs" ]]; then
    n_logs=$(ls -1 supplementary_code/logs/03_*.log 2>/dev/null | wc -l)
    if [[ "$n_logs" -ge 3 ]]; then
        log "  [REV 7] ✓ Anonymous package has ${n_logs} logs and README"
    else
        log "  [REV 7] [WARN] Expected ≥3 logs, found ${n_logs}"
        WARNINGS=$((WARNINGS+1))
    fi
else
    log "  [REV 7] [FAIL] supplementary_code/ incomplete"
    FAILURES=$((FAILURES+1))
fi
hr

# [REV 6] Sensitivity logs
if [[ "$SKIP_SENSITIVITY" != "1" ]]; then
    log "STEP 5d/6: Check sensitivity logs [REV 6]"
    n_gamma=$(ls -1 logs/sens_gamma_*.log 2>/dev/null | wc -l)
    n_sd=$(ls -1 logs/sens_sd_*_kappa*.log 2>/dev/null | wc -l)
    log "  [REV 6] γ logs: ${n_gamma} (expected 3)"
    log "  [REV 6] sd logs: ${n_sd} (expected 6 = 2 datasets × 3 κ)"
    if [[ "$n_gamma" -ne 3 ]]; then
        log "  [REV 6] [WARN] expected 3 γ logs"
        WARNINGS=$((WARNINGS+1))
    fi
    if [[ "$n_sd" -ne 6 ]]; then
        log "  [REV 6] [WARN] expected 6 sd logs"
        WARNINGS=$((WARNINGS+1))
    fi
    hr
fi

# ------------------------- cross-dataset summary ----------------------------
log "CROSS-DATASET SUMMARY (DiD, ml scenario)"
printf "  %-10s | %-30s | %-30s\n" "dataset" "DiD_s vs B4 (ml)" "DiD_w vs B4_w (ml)"
for ds in "${DATASETS[@]}"; do
    f="logs/03_${ds}.log"
    [[ -f "$f" ]] || continue
    b4=$(grep "Crossover DiD.*B4 (stats UB)" "$f" | head -1 | sed 's/^.*vs B4 (stats UB)[^:]*: //')
    b4w=$(grep "Crossover DiD.*B4_w" "$f" | head -1 | sed 's/^.*vs B4_w[^:]*: //')
    printf "  %-10s | %-30s | %-30s\n" "$ds" "$b4" "$b4w"
done
hr

# ------------------------- final status -------------------------------------
log "SUMMARY"
if [[ "$FAILURES" -gt 0 ]]; then
    log "  ${FAILURES} check(s) FAILED; ${WARNINGS} warning(s)"
    exit 1
elif [[ "$WARNINGS" -gt 0 ]]; then
    log "  ${WARNINGS} warning(s); no failures."
    exit 0
else
    log "  All checks passed."
fi